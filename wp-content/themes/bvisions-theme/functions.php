/**
 * Sets up theme defaults and registers support for various WordPress features.
 */
function bvisions_theme_setup() {
	// Make theme available for translation.
	load_theme_textdomain( 'bvisions-theme', get_template_directory() . '/languages' );

	// Add default posts and comments RSS feed links to head.
	add_theme_support( 'automatic-feed-links' );

	// Let WordPress manage the document title.
	add_theme_support( 'title-tag' );

	// Enable support for Post Thumbnails on posts and pages.
	add_theme_support( 'post-thumbnails' );

	// Register navigation menus.
	register_nav_menus(
		array(
			'primary' => esc_html__( 'Primary Menu', 'bvisions-theme' ),
		)
	);

	// Switch default core markup for search form, comment form, and comments to output valid HTML5.
	add_theme_support(
		'html5',
		array(
			'search-form',
			'comment-form',
			'comment-list',
			'gallery',
			'caption',
			'style',
			'script',
		)
	);

	// Add theme support for selective refresh for widgets.
	add_theme_support( 'customize-selective-refresh-widgets' );

	// Add support for core custom logo.
	add_theme_support(
		'custom-logo',
		array(
			'height'      => 250,
			'width'       => 250,
			'flex-width'  => true,
			'flex-height' => true,
		)
	);
}
add_action( 'after_setup_theme', 'bvisions_theme_setup' );


/**
 * Enqueue scripts and styles.
 */
function bvisions_theme_scripts() {
	// Enqueue main stylesheet.
	wp_enqueue_style( 'bvisions-theme-style', get_stylesheet_uri(), array(), _S_VERSION );

    // Enqueue Google Fonts (Updated to match static site)
    wp_enqueue_style( 'bvisions-theme-google-fonts', 'https://fonts.googleapis.com/css2?family=Khand:wght@400;700&family=Lustria&family=Rubik+Mono+One&family=Source+Code+Pro:wght@400;700&display=swap', array(), null );

	// Enqueue main JavaScript file.
    // Assumes script.js will be copied to theme's /js/ directory.
	wp_enqueue_script( 'bvisions-theme-script', get_template_directory_uri() . '/js/script.js', array(), _S_VERSION, true ); // Removed jQuery dependency

	if ( is_singular() && comments_open() && get_option( 'thread_comments' ) ) {
		wp_enqueue_script( 'comment-reply' );
	}
}
add_action( 'wp_enqueue_scripts', 'bvisions_theme_scripts' );

